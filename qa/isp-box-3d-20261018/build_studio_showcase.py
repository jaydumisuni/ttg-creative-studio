#!/usr/bin/env python3
"""Compose an actual 3D-mesh source clip inside TTG Creative Studio.

Source geometry is generated by render_3d_scene.py; typography, movement,
layer stack, poster, and final MP4 belong to native Creative Studio
TTGProject / ExportService / MotionExporter.
"""
from __future__ import annotations
import argparse
import copy
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT=Path(__file__).resolve().parents[2]
QA=Path(__file__).resolve().parent
sys.path.insert(0,str(ROOT/"src"))
from ttg_project_schema import TTGProject, Layer, Transform, Keyframe, CanvasSpec
from ttg_canvas_engine import RenderContext
from ttg_export_service import ExportService
from ttg_motion_exporter import MotionExporter
from ttg_ffmpeg_manager import FFmpegManager

FONT="/usr/share/fonts/truetype/lato/Lato-Heavy.ttf"
FONT_BOLD="/usr/share/fonts/truetype/lato/Lato-Bold.ttf"
FONT_REG="/usr/share/fonts/truetype/lato/Lato-Regular.ttf"
FILENAME="ispbox_3d_source.mp4"
DURATION=5.0
FPS=20


def title(name,text,x,y,size,color,delay=0.,font=FONT,shift=18):
    opacity=[Keyframe(0,0),Keyframe(delay,0),Keyframe(delay+.65,1,"ease_out")]
    pos=[Keyframe(0,[x-shift,y]),Keyframe(delay,[x-shift,y]),
         Keyframe(delay+.8,[x,y],"ease_out")]
    return Layer(id=name,type="text",name=name,
                 transform=Transform(x=x,y=y),
                 properties={"text":text,"size":size,"color":color,
                             "font_path":font,"shadow":False},
                 keyframes={"opacity":opacity,"position":pos})


def layers_for(scene_type):
    if scene_type=="motion":
        primary=Layer(id="true3d",type="video",name="Parametric 3D enclosure / camera orbit",
                      transform=Transform(),
                      properties={"path":"assets/"+FILENAME,
                                  "start":0,"source_in":0,"source_out":DURATION,
                                  "width":1280,"height":720,"speed":1})
    else:
        primary=Layer(id="true3d",type="image",name="Parametric 3D enclosure / poster",
                      transform=Transform(),
                      properties={"path":"assets/ispbox_3d_still.png"})
    return [primary,
            title("brand_line","THETECHGUY  /  DIGITAL SOLUTIONS",84,112,19,
                  "#90CBDA",.08,FONT_BOLD,16),
            title("hero_1","ENGINEERED",79,228,69,"#FAFCFF",.33,FONT,22),
            title("hero_2","TO PERFORM.",79,317,71,"#F4F7F5",.64,FONT,25),
            Layer(id="gold_rule",type="shape",name="Champagne titanium design rule",
                  transform=Transform(x=89,y=431),
                  properties={"shape":"rectangle","width":238,"height":4,
                              "fill":"#C9A471"},
                  keyframes={"opacity":[Keyframe(0,0),Keyframe(1.22,0),
                                          Keyframe(1.85,1)]}),
            title("product","TECHGUY   ISP BOX",88,464,32,"#D6EAF0",1.15,FONT_BOLD),
            title("signature","70 x 70 x 25 MM  /  CNC ALUMINIUM CONCEPT",89,518,18,
                  "#9BAAB5",1.48,FONT_REG),
            title("category","DIMENSIONAL PRODUCT FILM   //   2026",89,585,15,
                  "#75ABB9",1.82,FONT_REG),
            title("site","THETECHGUYDS.COM",88,667,16,
                  "#DAE9EE",2.05,FONT_BOLD)]


def project_create(kind):
    p=TTGProject(name="TECHGUY ISP BOX / CINEMATIC 3D PRODUCT CONCEPT",
                 project_type="motion" if kind=="motion" else "image",
                 canvas=CanvasSpec(width=1280,height=720,fps=FPS,
                                   duration=DURATION,background="#040A14"))
    p.layers=layers_for(kind)
    return p


def build_preview():
    (QA/"assets").mkdir(exist_ok=True)
    from render_3d_scene import render_frame
    render_frame(3.0).save(QA/"assets/ispbox_3d_still.png",optimize=True)
    project=project_create("poster")
    project.save(QA/"ispbox_3d_poster.ttgstudio.json")
    movie_project=project_create("motion")
    movie_project.save(QA/"ispbox_3d_motion.ttgstudio.json")
    film=MotionExporter(RenderContext(QA))
    poster=film.render_frame(project,3.0).convert("RGB")
    poster.save(QA/"ispbox_3d_poster.png",optimize=True)
    print("CREATIVE_STUDIO_POSTER",QA/"ispbox_3d_poster.png",flush=True)


def build_movie():
    ffmpeg=FFmpegManager().require()
    frames=QA/".scratch/frames"
    count=int(DURATION*FPS)
    for i in range(count):
        path=frames/f"shot_{i:04d}.png"
        if not path.is_file():
            raise RuntimeError("Missing genuine mesh frame "+path.name)
    # Encode the camera-animation source, then remove temporary frame PNGs
    # after a successful source render to avoid wasting KRATOS storage.
    target=QA/"assets"/FILENAME
    cmd=[ffmpeg,"-hide_banner","-loglevel","error","-y",
         "-framerate",str(FPS),"-i",str(frames/"shot_%04d.png"),
         "-c:v","libx264","-preset","medium","-crf","19","-pix_fmt","yuv420p",
         "-movflags","+faststart",str(target)]
    subprocess.run(cmd,check=True,timeout=180)
    assert target.stat().st_size>10000
    import shutil
    shutil.rmtree(frames)
    print("RAW_3D_MESH_FILM",target,target.stat().st_size,flush=True)
    movie=TTGProject.load(QA/"ispbox_3d_motion.ttgstudio.json")
    result=MotionExporter(RenderContext(QA)).export_mp4(
        movie,QA/"ispbox_3d_final.mp4",QA/".scratch/export"
    )
    print("CREATIVE_STUDIO_FINAL_MP4",result,result.stat().st_size,flush=True)


if __name__=="__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument("--phase",choices=["preview","film"],required=True)
    args=parser.parse_args()
    if args.phase=="preview":build_preview()
    else:build_movie()
